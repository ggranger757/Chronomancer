"""Build every sprite for CHRONOMANCER.
Heroes, the Mantis crew, Calloway and the Chronomancer: Step Quest sheets, recolored and redrawn (tools/build_sprites.py + costume.py).
Everyone else: the owner's base templates, dressed by tools/dress.py. Bernard: costume.bernard_ritual.
The Chronomancer and the Nanomancer: SHADOW Series bases (tools/shadow.py), when that folder is given.
usage: python3 tools/build_all.py <base-template folder> <Step-Quest folder> [SHADOW folder]"""
import sys, os, json, subprocess
from PIL import Image, ImageDraw
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
GIF, SQ = sys.argv[1], sys.argv[2]
OUT = os.path.join(ROOT, 'assets', 'sprites')
SHADOW = sys.argv[3] if len(sys.argv) > 3 else None
SQIDS = ['augie', 'jester', 'marquis', 'crew1', 'crew2', 'crew3', 'calloway'] + ([] if SHADOW else ['chrono'])
sys.path.insert(0, HERE)
import dress
npc = [k for k in dress.CAST if k not in SQIDS and k != 'mina']
subprocess.check_call([sys.executable, os.path.join(HERE, 'dress.py'), GIF, OUT, ','.join(npc)])
meta = json.load(open(os.path.join(OUT, '_dress_meta.json'))); os.remove(os.path.join(OUT, '_dress_meta.json'))
subprocess.check_call([sys.executable, os.path.join(HERE, 'build_sprites.py'), SQ, OUT, ','.join(SQIDS)])
meta.update(json.load(open(os.path.join(OUT, '_sq_meta.json')))); os.remove(os.path.join(OUT, '_sq_meta.json'))
if SHADOW:
    subprocess.check_call([sys.executable, os.path.join(HERE, 'shadow.py'), SHADOW, OUT])
    meta.update(json.load(open(os.path.join(OUT, '_shadow_meta.json')))); os.remove(os.path.join(OUT, '_shadow_meta.json'))
import costume
src = open(os.path.join(SQ, 'js/assets.js')).read()
J = json.loads(src[src.index('{', src.index('ASSETS')): src.rstrip().rstrip(';').rindex('}') + 1])
meta['bernard'] = costume.bernard_ritual(SQ, J, os.path.join(OUT, 'bernard.png'))
# Jester's shotgun row: his punch frames with a pump shotgun at the hand
m = meta['jester']; im = Image.open(os.path.join(OUT, 'jester.png')).convert('RGBA'); fw, fh = m['fw'], m['fh']
at = m['anims']['attack']; rows = im.height // fh
sheet = Image.new('RGBA', (im.width, (rows + 1) * fh)); sheet.paste(im, (0, 0))
an = []
for i in range(at['n']):
    fr = im.crop((i * fw, at['r'] * fh, (i + 1) * fw, (at['r'] + 1) * fh)); d = ImageDraw.Draw(fr)
    a = (at.get('an') or [None] * at['n'])[i] or {}
    bb = fr.getbbox(); y0, y1 = bb[1], bb[3]; ht = y1 - y0
    band = [(x, y) for y in range(y0 + int(ht * .22), y0 + int(ht * .42)) for x in range(fw) if fr.getpixel((x, y))[3]]
    hx, hy = max(band) if band else (int(fw * .62), int(fh * .62))
    hx -= 2
    INK = (16, 12, 20, 255)
    d.rectangle([hx - 10, hy - 1, hx - 1, hy + 2], fill=INK); d.rectangle([hx - 9, hy, hx - 2, hy + 1], fill=(106, 58, 30, 255))
    d.rectangle([hx - 1, hy - 2, hx + 19, hy + 1], fill=INK); d.line([hx, hy - 1, hx + 18, hy - 1], fill=(154, 164, 178, 255)); d.line([hx, hy, hx + 18, hy], fill=(64, 68, 78, 255))
    d.rectangle([hx + 5, hy + 1, hx + 10, hy + 3], fill=INK); d.line([hx + 6, hy + 2, hx + 9, hy + 2], fill=(106, 58, 30, 255))
    if i == at['n'] - 2:
        for (dx, dy, c) in ((0, 0, '#fff6c0'), (1, 0, '#ffd23a'), (2, 0, '#ff8a2a'), (1, -1, '#ffd23a'), (1, 1, '#ffd23a'), (3, 0, '#ff5a1a'), (2, -2, '#ff8a2a'), (2, 2, '#ff8a2a')):
            d.point((hx + 20 + dx, hy - 1 + dy), fill=c)
    sheet.paste(fr, (i * fw, rows * fh)); an.append(dict(a, muzzle=[hx + 20, hy - 1]))
sheet.save(os.path.join(OUT, 'jester.png'), optimize=True)
m['anims']['shoot'] = dict(r=rows, n=at['n'], b=at['b'], an=an)
open(os.path.join(ROOT, 'js', '01-sprites.js'), 'w').write('/* generated by tools/build_all.py — do not edit */\nwindow.TM = window.TM || {};\nTM.SPR = ' + json.dumps(meta) + ';\n')
print('sprites:', len(meta))
